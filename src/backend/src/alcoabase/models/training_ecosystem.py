class GapType(str, Enum):
    """Types of skill gaps identified during analysis."""

    MISSING_TRAINING = "missing_training"
    EXPIRED_TRAINING = "expired_training"
    NEW_VERSION_AVAILABLE = "new_version_available"


class PriorityLevel(str, Enum):
    """Priority levels for training items and skill gaps."""

    CRITICAL = "Critical"
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"


class MaterialType(str, Enum):
    """Types of AI-generated training materials."""

    EXECUTIVE_SUMMARY = "executive_summary"
    DETAILED_WALKTHROUGH = "detailed_walkthrough"
    KEY_TAKEAWAYS = "key_takeaways"
    PRESENTATION_OUTLINE = "presentation_outline"
    SAFETY_HIGHLIGHTS = "safety_highlights"


class QuestionType(str, Enum):
    """Types of AI-generated comprehension questions."""

    MULTIPLE_CHOICE = "multiple_choice"
    TRUE_FALSE = "true_false"
    SCENARIO_BASED = "scenario_based"
    FILL_IN_BLANK = "fill_in_blank"


class DifficultyLevel(str, Enum):
    """Difficulty levels for generated questions."""

    BASIC = "basic"
    INTERMEDIATE = "intermediate"
    ADVANCED = "advanced"


class SessionStatus(str, Enum):
    """Status of a virtual audit session."""

    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    ABANDONED = "abandoned"


class ContentStatus(str, Enum):
    """Status of AI-generated content (materials, questions)."""

    PENDING_REVIEW = "pending_review"
    APPROVED = "approved"
    REJECTED = "rejected"
    DRAFT = "draft"


