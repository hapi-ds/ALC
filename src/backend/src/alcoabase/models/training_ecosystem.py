"""Training ecosystem models for AI-enhanced training capabilities.

This module defines the database models for the AI-Enhanced Training Ecosystem
(Phase 5.3), including:
- TrainingSchedule: Personalized AI-generated training schedules
- SkillGap: Identified gaps between required and completed training
- TrainingMaterial: AI-generated educational content from SOPs
- GeneratedQuestion: AI-generated comprehension assessment questions
- VirtualAuditSession: Interactive role-play virtual audit sessions
- DynamicFeedbackCache: Cached paragraph-level feedback for incorrect answers

All models with AuditMixin are versioned via SQLAlchemy-Continuum for
full GxP audit trail compliance.

References:
    - ALCOA+ data integrity: attributable, legible, contemporaneous, original, accurate
    - Educational Specialist archetype (5.1) provides generation prompts
    - InferenceClient (4.3) handles all LLM inference calls
"""

from datetime import datetime
from enum import Enum
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSON, JSONB
from sqlalchemy.orm import Mapped, mapped_column

from alcoabase.database import Base
from alcoabase.models.audit import AuditMixin


