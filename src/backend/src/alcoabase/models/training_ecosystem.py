class TrainingSchedule(Base, AuditMixin):
    """Personalized AI-generated training schedule for a user.

    Each user has at most one active schedule per company. The schedule
    contains ordered training items with priorities, deadlines, and
    completion tracking. Schedules are regenerated on demand via the
    Educational Specialist agent archetype.

    Attributes:
        id: Primary key.
        user_id: Foreign key to the user this schedule belongs to.
        company_id: Foreign key to the owning company (tenant isolation).
        schedule_data: JSONB containing ordered training items with metadata.
        compliance_percentage: Computed percentage of completed training.
        total_items: Total number of training items in the schedule.
        completed_items: Number of completed training items.
        generated_at: Timestamp when the schedule was generated by AI.
        last_recalculated_at: Timestamp of last gap recalculation.
        created_at: Server-side UTC timestamp of creation.
        updated_at: Timestamp of last update.
    """

    __tablename__ = "training_schedules"
    __table_args__ = (
        UniqueConstraint(
            "user_id", "company_id", name="uq_training_schedule_user_company"
        ),
        CheckConstraint(
            "completed_items <= total_items",
            name="ck_schedule_completed_lte_total",
        ),
        Index("ix_training_schedule_user_company", "user_id", "company_id"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"))
    schedule_data: Mapped[dict] = mapped_column(JSONB)
    compliance_percentage: Mapped[float] = mapped_column(default=0.0)
    total_items: Mapped[int] = mapped_column(default=0)
    completed_items: Mapped[int] = mapped_column(default=0)
    generated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    last_recalculated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True)
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), onupdate=func.now(), nullable=True
    )


class SkillGap(Base):
    """Identified skill gap between required and completed training.

    Skill gaps are computed as the set difference of required documents
    (based on role assignments) minus completed training records. Gaps
    are created and resolved during periodic recalculation.

    Attributes:
        id: Primary key.
        user_id: Foreign key to the user with the gap.
        company_id: Foreign key to the owning company (tenant isolation).
        document_id: Foreign key to the document requiring training.
        document_version_id: Foreign key to the specific version required.
        gap_type: Classification of the gap (missing, expired, new version).
        priority: Computed priority level based on deadline and access gating.
        days_overdue: Number of days past the training deadline (nullable).
        blocks_access: Whether this gap blocks document access.
        identified_at: Timestamp when the gap was first identified.
        resolved_at: Timestamp when the gap was resolved (nullable).
        created_at: Server-side UTC timestamp of creation.
    """

    __tablename__ = "skill_gaps"
    __table_args__ = (
        UniqueConstraint(
            "user_id",
            "document_id",
            "document_version_id",
            "gap_type",
            name="uq_skill_gap_user_doc_version_type",
        ),
        Index("ix_skill_gap_user_company", "user_id", "company_id"),
        Index(
            "ix_skill_gap_document", "document_id", "document_version_id"
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"))
    document_id: Mapped[int] = mapped_column(ForeignKey("documents.id"))
    document_version_id: Mapped[int] = mapped_column(
        ForeignKey("document_versions.id")
    )
    gap_type: Mapped[GapType] = mapped_column()
    priority: Mapped[PriorityLevel] = mapped_column()
    days_overdue: Mapped[int | None] = mapped_column(nullable=True, default=0)
    blocks_access: Mapped[bool] = mapped_column(default=False)
    identified_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    resolved_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )


class TrainingMaterial(Base, AuditMixin):
    """AI-generated training material from a source document.

    Materials are generated by the Educational Specialist agent archetype
    and must pass coordinator review before being presented to trainees.
    Each document version can have one material per type.

    Attributes:
        id: Primary key.
        document_id: Foreign key to the source document.
        document_version_id: Foreign key to the specific version used.
        company_id: Foreign key to the owning company (tenant isolation).
        material_type: Type of material (summary, walkthrough, etc.).
        content_data: JSONB containing the structured material content.
        learning_objectives: JSON list of learning objectives.
        estimated_duration_minutes: Estimated time to complete the material.
        status: Review status (pending_review, approved, rejected, draft).
        generated_by_agent_id: ID of the agent archetype that generated this.
        inference_duration_ms: Time taken for LLM inference in milliseconds.
        reviewed_by: Foreign key to the reviewer user (nullable).
        reviewed_at: Timestamp of review (nullable).
        created_at: Server-side UTC timestamp of creation.
        updated_at: Timestamp of last update.
    """

    __tablename__ = "training_materials"
    __table_args__ = (
        UniqueConstraint(
            "document_id",
            "document_version_id",
            "material_type",
            name="uq_training_material_doc_version_type",
        ),
        Index(
            "ix_training_material_doc_version",
            "document_id",
            "document_version_id",
        ),
        Index("ix_training_material_status", "status"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    document_id: Mapped[int] = mapped_column(ForeignKey("documents.id"))
    document_version_id: Mapped[int] = mapped_column(
        ForeignKey("document_versions.id")
    )
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"))
    material_type: Mapped[MaterialType] = mapped_column()
    content_data: Mapped[dict] = mapped_column(JSONB)
    learning_objectives: Mapped[list] = mapped_column(JSON)
    estimated_duration_minutes: Mapped[int] = mapped_column()
    status: Mapped[str] = mapped_column(
        String(20), default=ContentStatus.PENDING_REVIEW.value
    )
    generated_by_agent_id: Mapped[str | None] = mapped_column(
        String(255), nullable=True
    )
    inference_duration_ms: Mapped[int | None] = mapped_column(nullable=True)
    reviewed_by: Mapped[int | None] = mapped_column(
        ForeignKey("users.id"), nullable=True
    )
    reviewed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    updated_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), onupdate=func.now(), nullable=True
    )

    def __init__(self, **kwargs: Any) -> None:
        """Initialize TrainingMaterial with pending_review status default."""
        if "status" not in kwargs:
            kwargs["status"] = ContentStatus.PENDING_REVIEW.value
        super().__init__(**kwargs)


class GeneratedQuestion(Base, AuditMixin):
    """AI-generated comprehension question for training assessments.

    Questions are generated from source documents with validated answers,
    section references, and difficulty levels. They must pass coordinator
    review before being served in active assessments.

    Attributes:
        id: Primary key.
        document_id: Foreign key to the source document.
        document_version_id: Foreign key to the specific version used.
        company_id: Foreign key to the owning company (tenant isolation).
        question_text: The full question text.
        question_type: Type of question (MC, T/F, scenario, fill-in-blank).
        correct_answer: The correct answer text.
        distractors: JSON list of incorrect answer options (for MC).
        explanation: Explanation of why the answer is correct.
        difficulty_level: Question difficulty (basic, intermediate, advanced).
        bloom_taxonomy_level: Bloom's taxonomy classification.
        sop_section_ref: Reference to the source SOP section.
        status: Review status (pending_review, approved, rejected, draft).
        reviewed_by: Foreign key to the reviewer user (nullable).
        reviewed_at: Timestamp of review (nullable).
        created_at: Server-side UTC timestamp of creation.
        updated_at: Timestamp of last update.
    """

    __tablename__ = "generated_questions"
    __table_args__ = (
        Index(
            "ix_generated_question_doc_version",
            "document_id",
            "document_version_id",
        ),
        Index("ix_generated_question_status", "status"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    document_id: Mapped[int] = mapped_column(ForeignKey("documents.id"))
    document_version_id: Mapped[int] = mapped_column(
        ForeignKey("document_versions.id")
    )
    company_id: Mapped[int] = mapped_column(ForeignKey("companies.id"))
